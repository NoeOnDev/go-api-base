// Package categories is the first half of the catalog example: public reads, writes only for
// administrators, a unique value (slug) that responds 409 if it is repeated and a relationship
// with products that prevents deleting a category in use.
package categories

import (
	"errors"
	"fmt"
	"net/http"
	"time"

	"github.com/jackc/pgx/v5"

	"github.com/NoeOnDev/go-api-base/internal/db"
	"github.com/NoeOnDev/go-api-base/internal/httpx"
	"github.com/NoeOnDev/go-api-base/internal/store"
)

// Handler groups the category endpoints.
type Handler struct {
	q *store.Queries
}

// NewHandler creates the handler from the queries generated by sqlc.
func NewHandler(q *store.Queries) *Handler {
	return &Handler{q: q}
}

type categoryResponse struct {
	ID        int64     `json:"id"`
	Name      string    `json:"name"`
	Slug      string    `json:"slug"`
	CreatedAt time.Time `json:"created_at"`
	UpdatedAt time.Time `json:"updated_at"`
}

func toResponse(c store.Category) categoryResponse {
	return categoryResponse{ID: c.ID, Name: c.Name, Slug: c.Slug, CreatedAt: c.CreatedAt, UpdatedAt: c.UpdatedAt}
}

var (
	errNotFound  = httpx.NotFound("category_not_found")
	errSlugTaken = httpx.Conflict("slug_taken", "slug")
	errInUse     = httpx.Conflict("category_in_use", "")
)

// list answers GET /categories?limit=20&offset=0, sorted by name.
func (h *Handler) list(w http.ResponseWriter, r *http.Request) error {
	page, err := httpx.ParsePage(r)
	if err != nil {
		return err
	}

	categories, err := h.q.ListCategories(r.Context(), store.ListCategoriesParams{Limit: page.Limit, Offset: page.Offset})
	if err != nil {
		return fmt.Errorf("list categories: %w", err)
	}
	total, err := h.q.CountCategories(r.Context())
	if err != nil {
		return fmt.Errorf("count categories: %w", err)
	}

	data := make([]categoryResponse, len(categories))
	for i, c := range categories {
		data[i] = toResponse(c)
	}

	httpx.Write(w, http.StatusOK, httpx.List[categoryResponse]{
		Data: data,
		Meta: httpx.PageMeta{Limit: page.Limit, Offset: page.Offset, Total: total},
	})
	return nil
}

// get answers GET /categories/{id}.
func (h *Handler) get(w http.ResponseWriter, r *http.Request) error {
	id, err := httpx.PathID(r, "id")
	if err != nil {
		return err
	}

	c, err := h.q.GetCategory(r.Context(), id)
	if errors.Is(err, pgx.ErrNoRows) {
		return errNotFound
	}
	if err != nil {
		return fmt.Errorf("get category %d: %w", id, err)
	}

	httpx.Write(w, http.StatusOK, toResponse(c))
	return nil
}

// create answers POST /categories.
func (h *Handler) create(w http.ResponseWriter, r *http.Request) error {
	var in categoryInput
	if err := httpx.Decode(w, r, &in); err != nil {
		return err
	}
	in.normalize()
	if err := in.validate(); err != nil {
		return err
	}

	c, err := h.q.CreateCategory(r.Context(), store.CreateCategoryParams{Name: in.Name, Slug: in.Slug})
	if _, ok := db.IsUniqueViolation(err); ok {
		return errSlugTaken
	}
	if err != nil {
		return fmt.Errorf("create category: %w", err)
	}

	w.Header().Set("Location", fmt.Sprintf("/categories/%d", c.ID))
	httpx.Write(w, http.StatusCreated, toResponse(c))
	return nil
}

// update answers PUT /categories/{id}.
func (h *Handler) update(w http.ResponseWriter, r *http.Request) error {
	id, err := httpx.PathID(r, "id")
	if err != nil {
		return err
	}

	var in categoryInput
	if err := httpx.Decode(w, r, &in); err != nil {
		return err
	}
	in.normalize()
	if err := in.validate(); err != nil {
		return err
	}

	c, err := h.q.UpdateCategory(r.Context(), store.UpdateCategoryParams{ID: id, Name: in.Name, Slug: in.Slug})
	if errors.Is(err, pgx.ErrNoRows) {
		return errNotFound
	}
	if _, ok := db.IsUniqueViolation(err); ok {
		return errSlugTaken
	}
	if err != nil {
		return fmt.Errorf("update category %d: %w", id, err)
	}

	httpx.Write(w, http.StatusOK, toResponse(c))
	return nil
}

// delete answers DELETE /categories/{id}. If the category has products it responds 409: the
// database prevents it with the ON DELETE RESTRICT constraint of products.category_id.
func (h *Handler) delete(w http.ResponseWriter, r *http.Request) error {
	id, err := httpx.PathID(r, "id")
	if err != nil {
		return err
	}

	rows, err := h.q.DeleteCategory(r.Context(), id)
	if _, ok := db.IsForeignKeyViolation(err); ok {
		return errInUse
	}
	if err != nil {
		return fmt.Errorf("delete category %d: %w", id, err)
	}
	if rows == 0 {
		return errNotFound
	}

	httpx.Write(w, http.StatusNoContent, nil)
	return nil
}
