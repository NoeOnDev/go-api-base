// Package notes is the template's example resource: a complete CRUD that shows the pattern to
// follow (queries with sqlc, validation, errors and tests).
// To create a new resource, copy this package and adapt it (see docs/adding-a-resource.md).
//
// It also shows ownership: each note belongs to a user, and every query filters by the session's
// user. If someone asks for another user's note, the query does not find it and the API responds
// 404 (not 403), so as not to reveal that the note exists.
//
// And real time: each change is published on the owner's channel (note.created, note.updated,
// note.deleted), so another tab or device updates without reloading. For shared data (a board,
// a project) it is published on a topic; see docs/realtime.md.
package notes

import (
	"errors"
	"fmt"
	"net/http"
	"time"

	"github.com/jackc/pgx/v5"

	"github.com/NoeOnDev/go-api-base/internal/auth"
	"github.com/NoeOnDev/go-api-base/internal/httpx"
	"github.com/NoeOnDev/go-api-base/internal/realtime"
	"github.com/NoeOnDev/go-api-base/internal/store"
)

// Handler groups the note endpoints and their dependencies.
type Handler struct {
	q      *store.Queries
	broker *realtime.Broker
}

// NewHandler creates the handler from the queries generated by sqlc and the real-time event
// broker.
func NewHandler(q *store.Queries, broker *realtime.Broker) *Handler {
	return &Handler{q: q, broker: broker}
}

// Events published on the note owner's channel.
const (
	EventCreated = "note.created" // with the note
	EventUpdated = "note.updated" // with the note
	EventDeleted = "note.deleted" // with {"id": …}
)

// noteResponse is what the API returns. It is kept apart from store.Note so that a change in
// the table does not change the contract with the frontend without you deciding it.
type noteResponse struct {
	ID        int64     `json:"id"`
	Title     string    `json:"title"`
	Body      string    `json:"body"`
	CreatedAt time.Time `json:"created_at"`
	UpdatedAt time.Time `json:"updated_at"`
}

func toResponse(n store.Note) noteResponse {
	return noteResponse{
		ID:        n.ID,
		Title:     n.Title,
		Body:      n.Body,
		CreatedAt: n.CreatedAt,
		UpdatedAt: n.UpdatedAt,
	}
}

var errNotFound = httpx.NotFound("note_not_found")

// list answers GET /notes?limit=20&offset=0.
func (h *Handler) list(w http.ResponseWriter, r *http.Request) error {
	page, err := httpx.ParsePage(r)
	if err != nil {
		return err
	}

	user := auth.MustUser(r.Context())

	notes, err := h.q.ListNotes(r.Context(), store.ListNotesParams{UserID: user.ID, Limit: page.Limit, Offset: page.Offset})
	if err != nil {
		return fmt.Errorf("list notes: %w", err)
	}

	total, err := h.q.CountNotes(r.Context(), user.ID)
	if err != nil {
		return fmt.Errorf("count notes: %w", err)
	}

	data := make([]noteResponse, len(notes))
	for i, n := range notes {
		data[i] = toResponse(n)
	}

	httpx.Write(w, http.StatusOK, httpx.List[noteResponse]{
		Data: data,
		Meta: httpx.PageMeta{Limit: page.Limit, Offset: page.Offset, Total: total},
	})
	return nil
}

// get answers GET /notes/{id}.
func (h *Handler) get(w http.ResponseWriter, r *http.Request) error {
	id, err := httpx.PathID(r, "id")
	if err != nil {
		return err
	}

	note, err := h.q.GetNote(r.Context(), store.GetNoteParams{ID: id, UserID: auth.MustUser(r.Context()).ID})
	if errors.Is(err, pgx.ErrNoRows) {
		return errNotFound
	}
	if err != nil {
		return fmt.Errorf("get note %d: %w", id, err)
	}

	httpx.Write(w, http.StatusOK, toResponse(note))
	return nil
}

// create answers POST /notes.
func (h *Handler) create(w http.ResponseWriter, r *http.Request) error {
	var in noteInput
	if err := httpx.Decode(w, r, &in); err != nil {
		return err
	}
	in.normalize()
	if err := in.validate(); err != nil {
		return err
	}

	note, err := h.q.CreateNote(r.Context(), store.CreateNoteParams{
		UserID: auth.MustUser(r.Context()).ID,
		Title:  in.Title,
		Body:   in.Body,
	})
	if err != nil {
		return fmt.Errorf("create note: %w", err)
	}

	h.broker.PublishToUser(r.Context(), note.UserID, realtime.Event{Type: EventCreated, Data: toResponse(note)})

	w.Header().Set("Location", fmt.Sprintf("/notes/%d", note.ID))
	httpx.Write(w, http.StatusCreated, toResponse(note))
	return nil
}

// update answers PUT /notes/{id}. It replaces the whole note.
func (h *Handler) update(w http.ResponseWriter, r *http.Request) error {
	id, err := httpx.PathID(r, "id")
	if err != nil {
		return err
	}

	var in noteInput
	if err := httpx.Decode(w, r, &in); err != nil {
		return err
	}
	in.normalize()
	if err := in.validate(); err != nil {
		return err
	}

	note, err := h.q.UpdateNote(r.Context(), store.UpdateNoteParams{
		ID:     id,
		UserID: auth.MustUser(r.Context()).ID,
		Title:  in.Title,
		Body:   in.Body,
	})
	if errors.Is(err, pgx.ErrNoRows) {
		return errNotFound
	}
	if err != nil {
		return fmt.Errorf("update note %d: %w", id, err)
	}

	h.broker.PublishToUser(r.Context(), note.UserID, realtime.Event{Type: EventUpdated, Data: toResponse(note)})
	httpx.Write(w, http.StatusOK, toResponse(note))
	return nil
}

// delete answers DELETE /notes/{id}.
func (h *Handler) delete(w http.ResponseWriter, r *http.Request) error {
	id, err := httpx.PathID(r, "id")
	if err != nil {
		return err
	}

	user := auth.MustUser(r.Context())
	rows, err := h.q.DeleteNote(r.Context(), store.DeleteNoteParams{ID: id, UserID: user.ID})
	if err != nil {
		return fmt.Errorf("delete note %d: %w", id, err)
	}
	if rows == 0 {
		return errNotFound
	}

	h.broker.PublishToUser(r.Context(), user.ID, realtime.Event{Type: EventDeleted, Data: map[string]int64{"id": id}})

	httpx.Write(w, http.StatusNoContent, nil)
	return nil
}
