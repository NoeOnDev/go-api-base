// Package products is the second half of the catalog example. Besides the notes pattern, it
// shows how to:
//   - show more data depending on who asks: visitors only see active products, the admin sees all;
//   - relate tables: each product belongs to a category and the response includes it (JOIN);
//   - filter and search a list with optional parameters;
//   - translate database errors: repeated slug → 409, missing category → 422.
package products

import (
	"context"
	"errors"
	"fmt"
	"net/http"
	"time"

	"github.com/jackc/pgx/v5"

	"github.com/NoeOnDev/go-api-base/internal/auth"
	"github.com/NoeOnDev/go-api-base/internal/db"
	"github.com/NoeOnDev/go-api-base/internal/httpx"
	"github.com/NoeOnDev/go-api-base/internal/i18n"
	"github.com/NoeOnDev/go-api-base/internal/store"
)

// Handler groups the product endpoints.
type Handler struct {
	q *store.Queries
}

// NewHandler creates the handler from the queries generated by sqlc.
func NewHandler(q *store.Queries) *Handler {
	return &Handler{q: q}
}

type categoryRef struct {
	ID   int64  `json:"id"`
	Name string `json:"name"`
}

type productResponse struct {
	ID          int64       `json:"id"`
	Category    categoryRef `json:"category"`
	Name        string      `json:"name"`
	Slug        string      `json:"slug"`
	Description string      `json:"description"`
	PriceCents  int64       `json:"price_cents"`
	Stock       int32       `json:"stock"`
	Active      bool        `json:"active"`
	CreatedAt   time.Time   `json:"created_at"`
	UpdatedAt   time.Time   `json:"updated_at"`
}

// toResponse takes the GetProduct row. ListProductsRow has the same fields, so it is converted
// with store.GetProductRow(row).
func toResponse(p store.GetProductRow) productResponse {
	return productResponse{
		ID:          p.ID,
		Category:    categoryRef{ID: p.CategoryID, Name: p.CategoryName},
		Name:        p.Name,
		Slug:        p.Slug,
		Description: p.Description,
		PriceCents:  p.PriceCents,
		Stock:       p.Stock,
		Active:      p.Active,
		CreatedAt:   p.CreatedAt,
		UpdatedAt:   p.UpdatedAt,
	}
}

var (
	errNotFound   = httpx.NotFound("product_not_found")
	errSlugTaken  = httpx.Conflict("slug_taken", "slug")
	errNoCategory = httpx.Validation(httpx.Fields{"category_id": i18n.M("validation.unknown_category")})
)

// writeError translates the database errors that depend on the data sent.
func writeError(err error, action string) error {
	if _, ok := db.IsUniqueViolation(err); ok {
		return errSlugTaken
	}
	if _, ok := db.IsForeignKeyViolation(err); ok {
		return errNoCategory
	}
	return fmt.Errorf("%s: %w", action, err)
}

// list answers GET /products?limit=20&offset=0&category_id=3&q=café&active=true.
func (h *Handler) list(w http.ResponseWriter, r *http.Request) error {
	page, err := httpx.ParsePage(r)
	if err != nil {
		return err
	}
	f, err := parseFilters(r)
	if err != nil {
		return err
	}

	// Only the admin sees the inactive products (and can filter them with ?active=false).
	// For everyone else, the list is always of active products.
	if !isAdmin(r) {
		active := true
		f.Active = &active
	}

	rows, err := h.q.ListProducts(r.Context(), store.ListProductsParams{
		CategoryID: f.CategoryID,
		Search:     f.Search,
		Active:     f.Active,
		Limit:      page.Limit,
		Offset:     page.Offset,
	})
	if err != nil {
		return fmt.Errorf("list products: %w", err)
	}

	total, err := h.q.CountProducts(r.Context(), store.CountProductsParams{
		CategoryID: f.CategoryID,
		Search:     f.Search,
		Active:     f.Active,
	})
	if err != nil {
		return fmt.Errorf("count products: %w", err)
	}

	data := make([]productResponse, len(rows))
	for i, row := range rows {
		data[i] = toResponse(store.GetProductRow(row))
	}

	httpx.Write(w, http.StatusOK, httpx.List[productResponse]{
		Data: data,
		Meta: httpx.PageMeta{Limit: page.Limit, Offset: page.Offset, Total: total},
	})
	return nil
}

// get answers GET /products/{id}.
func (h *Handler) get(w http.ResponseWriter, r *http.Request) error {
	id, err := httpx.PathID(r, "id")
	if err != nil {
		return err
	}

	p, err := h.q.GetProduct(r.Context(), id)
	if errors.Is(err, pgx.ErrNoRows) {
		return errNotFound
	}
	if err != nil {
		return fmt.Errorf("get product %d: %w", id, err)
	}

	// An inactive product does not exist for someone who is not an admin.
	if !p.Active && !isAdmin(r) {
		return errNotFound
	}

	httpx.Write(w, http.StatusOK, toResponse(p))
	return nil
}

// isAdmin reports whether the request comes from an administrator. The public product routes
// use auth.OptionalUser, so there may or may not be a user.
func isAdmin(r *http.Request) bool {
	u, ok := auth.UserFrom(r.Context())
	return ok && u.IsAdmin()
}

// create answers POST /products.
func (h *Handler) create(w http.ResponseWriter, r *http.Request) error {
	var in productInput
	if err := httpx.Decode(w, r, &in); err != nil {
		return err
	}
	in.normalize()
	if err := in.validate(); err != nil {
		return err
	}

	id, err := h.q.CreateProduct(r.Context(), store.CreateProductParams{
		CategoryID:  in.CategoryID,
		Name:        in.Name,
		Slug:        in.Slug,
		Description: in.Description,
		PriceCents:  in.PriceCents,
		Stock:       in.Stock,
		Active:      *in.Active,
	})
	if err != nil {
		return writeError(err, "create product")
	}

	w.Header().Set("Location", fmt.Sprintf("/products/%d", id))
	return h.writeProduct(r.Context(), w, http.StatusCreated, id)
}

// update answers PUT /products/{id}. It replaces the whole product.
func (h *Handler) update(w http.ResponseWriter, r *http.Request) error {
	id, err := httpx.PathID(r, "id")
	if err != nil {
		return err
	}

	var in productInput
	if err := httpx.Decode(w, r, &in); err != nil {
		return err
	}
	in.normalize()
	if err := in.validate(); err != nil {
		return err
	}

	_, err = h.q.UpdateProduct(r.Context(), store.UpdateProductParams{
		ID:          id,
		CategoryID:  in.CategoryID,
		Name:        in.Name,
		Slug:        in.Slug,
		Description: in.Description,
		PriceCents:  in.PriceCents,
		Stock:       in.Stock,
		Active:      *in.Active,
	})
	if errors.Is(err, pgx.ErrNoRows) {
		return errNotFound
	}
	if err != nil {
		return writeError(err, fmt.Sprintf("update product %d", id))
	}

	return h.writeProduct(r.Context(), w, http.StatusOK, id)
}

// delete answers DELETE /products/{id}.
func (h *Handler) delete(w http.ResponseWriter, r *http.Request) error {
	id, err := httpx.PathID(r, "id")
	if err != nil {
		return err
	}

	rows, err := h.q.DeleteProduct(r.Context(), id)
	if err != nil {
		return fmt.Errorf("delete product %d: %w", id, err)
	}
	if rows == 0 {
		return errNotFound
	}

	httpx.Write(w, http.StatusNoContent, nil)
	return nil
}

// writeProduct reads the product with its category and responds with it.
// Create and update only return the id, so the same query with the JOIN is reused.
func (h *Handler) writeProduct(ctx context.Context, w http.ResponseWriter, status int, id int64) error {
	p, err := h.q.GetProduct(ctx, id)
	if errors.Is(err, pgx.ErrNoRows) {
		return errNotFound
	}
	if err != nil {
		return fmt.Errorf("get product %d: %w", id, err)
	}

	httpx.Write(w, status, toResponse(p))
	return nil
}
